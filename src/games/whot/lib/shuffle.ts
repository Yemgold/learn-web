




/* ============================================================
   LEARNYFI WHOT — SHUFFLE UTILITIES
   ============================================================

   Provides:
   - Fisher-Yates array shuffling
   - Seeded shuffling for repeatable tests
   - Random item selection
   - Random integer generation
   - Safe array shuffling without mutating the original

   Frontend-only. No dependencies.
   ============================================================ */

/**
 * Random number generator contract.
 *
 * Must return a number greater than or equal to 0 and less
 * than 1, just like Math.random().
 */
export type WhotRandom = () => number;

/**
 * Default random number generator.
 */
export const whotRandom: WhotRandom = () => Math.random();

/**
 * Validates a random number generated by an injected RNG.
 */
function getRandomValue(random: WhotRandom): number {
  const value = random();

  if (!Number.isFinite(value) || value < 0 || value >= 1) {
    throw new Error(
      "[Learnyfi WHOT] Random generator must return a number in [0, 1).",
    );
  }

  return value;
}

/* ============================================================
   SHUFFLE
   ============================================================ */

/**
 * Shuffles an array using the Fisher-Yates algorithm.
 *
 * The original array is never mutated.
 *
 * Example:
 * const shuffledCards = shuffleArray(cards);
 */
export function shuffleArray<T>(
  items: readonly T[],
  random: WhotRandom = whotRandom,
): T[] {
  const shuffled = [...items];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(
      getRandomValue(random) * (index + 1),
    );

    [shuffled[index], shuffled[swapIndex]] = [
      shuffled[swapIndex],
      shuffled[index],
    ];
  }

  return shuffled;
}

/**
 * Alias for callers that prefer the shorter function name.
 */
export const shuffle = shuffleArray;

/* ============================================================
   SEEDED RANDOM GENERATOR
   ============================================================ */

/**
 * Creates a deterministic pseudo-random generator from a seed.
 *
 * The same seed produces the same sequence of random numbers,
 * which is useful for tests and debugging.
 *
 * This is not cryptographically secure and should not be used
 * for security-sensitive randomness.
 */
export function createSeededRandom(seed: number): WhotRandom {
  if (!Number.isFinite(seed)) {
    throw new Error(
      "[Learnyfi WHOT] Seed must be a finite number.",
    );
  }

  let state = seed >>> 0;

  return () => {
    state += 0x6d2b79f5;

    let value = state;

    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);

    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Shuffles an array deterministically using a seed.
 */
export function seededShuffle<T>(
  items: readonly T[],
  seed: number,
): T[] {
  return shuffleArray(items, createSeededRandom(seed));
}

/* ============================================================
   RANDOM INTEGER
   ============================================================ */

/**
 * Returns a random integer in the inclusive range [minimum, maximum].
 */
export function randomInt(
  minimum: number,
  maximum: number,
  random: WhotRandom = whotRandom,
): number {
  if (!Number.isInteger(minimum) || !Number.isInteger(maximum)) {
    throw new Error(
      "[Learnyfi WHOT] Random integer bounds must be integers.",
    );
  }

  if (maximum < minimum) {
    throw new Error(
      "[Learnyfi WHOT] Maximum must be greater than or equal to minimum.",
    );
  }

  return (
    minimum +
    Math.floor(getRandomValue(random) * (maximum - minimum + 1))
  );
}

/* ============================================================
   RANDOM ITEM
   ============================================================ */

/**
 * Returns a random item from an array.
 *
 * Returns undefined for an empty array.
 */
export function pickRandom<T>(
  items: readonly T[],
  random: WhotRandom = whotRandom,
): T | undefined {
  if (items.length === 0) {
    return undefined;
  }

  return items[randomInt(0, items.length - 1, random)];
}

/**
 * Returns a random item while also returning the remaining items.
 *
 * The source array remains unchanged.
 */
export function drawRandomItem<T>(
  items: readonly T[],
  random: WhotRandom = whotRandom,
): {
  item: T | undefined;
  remaining: T[];
} {
  if (items.length === 0) {
    return {
      item: undefined,
      remaining: [],
    };
  }

  const index = randomInt(0, items.length - 1, random);

  return {
    item: items[index],
    remaining: [
      ...items.slice(0, index),
      ...items.slice(index + 1),
    ],
  };
}

/* ============================================================
   RANDOM BOOLEAN
   ============================================================ */

/**
 * Returns true with the supplied probability.
 *
 * probability:
 * - 0 means always false
 * - 0.5 means approximately 50/50
 * - 1 means always true
 */
export function randomChance(
  probability: number,
  random: WhotRandom = whotRandom,
): boolean {
  if (
    !Number.isFinite(probability) ||
    probability < 0 ||
    probability > 1
  ) {
    throw new Error(
      "[Learnyfi WHOT] Probability must be between 0 and 1.",
    );
  }

  if (probability === 0) return false;
  if (probability === 1) return true;

  return getRandomValue(random) < probability;
}

/* ============================================================
   ARRAY HELPERS
   ============================================================ */

/**
 * Returns a shuffled copy containing up to `count` items.
 *
 * Useful for selecting a random sample of questions.
 */
export function sampleRandom<T>(
  items: readonly T[],
  count: number,
  random: WhotRandom = whotRandom,
): T[] {
  if (!Number.isInteger(count) || count < 0) {
    throw new Error(
      "[Learnyfi WHOT] Sample count must be a non-negative integer.",
    );
  }

  return shuffleArray(items, random).slice(
    0,
    Math.min(count, items.length),
  );
}

/**
 * Returns a shuffled copy of an array, keeping the original intact.
 */
export function shuffledCopy<T>(
  items: readonly T[],
): T[] {
  return shuffleArray(items);
}
